/* Site search for The Reassuring Universe.
   Runs entirely in the reader's browser over window.SEARCH_INDEX
   (assets/search-index.js, generated by site_data/generate_site.py).
   A result must contain every word of the query (or each "quoted phrase")
   in its title or text. Matching ignores case, accents, and curly vs.
   straight quotes and dashes. */
(function () {
  "use strict";
  var docs = window.SEARCH_INDEX || [];
  var form = document.getElementById("search-form");
  var input = document.getElementById("search-q");
  var status = document.getElementById("search-status");
  var results = document.getElementById("search-results");
  if (!form || !input || !results) return;

  // One character in, one character out, so positions in the normalized
  // text line up with positions in the original text (used for snippets).
  function fold(ch) {
    switch (ch) {
      case "‘": case "’": return "'";
      case "“": case "”": return '"';
      case "–": case "—": return "-";
      case "…": return ".";
    }
    var d = ch.normalize ? ch.normalize("NFD").charAt(0) : ch;
    var l = d.toLowerCase();
    return l.length === 1 ? l : d;
  }
  function norm(s) {
    var out = "";
    for (var i = 0; i < s.length; i++) out += fold(s.charAt(i));
    return out;
  }
  docs.forEach(function (d) { d.nt = norm(d.title); d.nx = norm(d.text); });

  function parseQuery(q) {
    var terms = [], re = /"([^"]+)"|(\S+)/g, m;
    var nq = norm(q);
    while ((m = re.exec(nq)) !== null) {
      var t = (m[1] !== undefined ? m[1] : m[2]).replace(/\s+/g, " ").trim();
      if (m[2] !== undefined) t = t.replace(/^[^\w']+|[^\w']+$/g, "");
      if (t.length) terms.push(t);
    }
    return terms;
  }

  function isWordStart(hay, i) {
    return i === 0 || !/[a-z0-9]/.test(hay.charAt(i - 1));
  }
  // Occurrences of needle that begin at the start of a word (so "faith" also
  // finds "faithful", but "art" does not find "heart").
  function countOf(hay, needle) {
    var n = 0, i = hay.indexOf(needle);
    while (i !== -1 && n < 50) {
      if (isWordStart(hay, i)) n++;
      i = hay.indexOf(needle, i + 1);
    }
    return n;
  }
  function firstOf(hay, needle) {
    var i = hay.indexOf(needle);
    while (i !== -1 && !isWordStart(hay, i)) i = hay.indexOf(needle, i + 1);
    return i;
  }

  function search(q) {
    var terms = parseQuery(q);
    if (!terms.length) return { terms: terms, hits: [] };
    // Rarer words count for more (so "fear" outweighs "not"), and pieces that
    // contain the whole query as a phrase, or match in the title, come first.
    var N = docs.length, phrase = terms.length > 1 ? terms.join(" ") : null;
    var idf = terms.map(function (t) {
      var df = 0;
      docs.forEach(function (d) { if (firstOf(d.nt, t) !== -1 || firstOf(d.nx, t) !== -1) df++; });
      return Math.log(1 + N / Math.max(1, df));
    });
    var hits = [];
    docs.forEach(function (d) {
      var score = 0;
      for (var i = 0; i < terms.length; i++) {
        var inTitle = firstOf(d.nt, terms[i]) !== -1;
        var inText = countOf(d.nx, terms[i]);
        if (!inTitle && !inText) return;
        score += idf[i] * ((inTitle ? 6 : 0) + Math.log(1 + inText));
      }
      if (phrase) {
        var pc = countOf(d.nx, phrase) + (firstOf(d.nt, phrase) !== -1 ? 3 : 0);
        if (pc) score += 10 + 3 * Math.log(1 + pc);
      }
      hits.push({ doc: d, score: score });
    });
    hits.sort(function (a, b) { return b.score - a.score || a.doc.title.localeCompare(b.doc.title); });
    return { terms: terms, phrase: phrase, hits: hits };
  }

  // Append text to el, wrapping every occurrence of any term in <mark>.
  function appendMarked(el, text, terms) {
    var nt = norm(text), pos = 0;
    while (pos < text.length) {
      var best = -1, len = 0;
      for (var i = 0; i < terms.length; i++) {
        var j = nt.indexOf(terms[i], pos);
        while (j !== -1 && !isWordStart(nt, j)) j = nt.indexOf(terms[i], j + 1);
        if (j !== -1 && (best === -1 || j < best || (j === best && terms[i].length > len))) { best = j; len = terms[i].length; }
      }
      if (best === -1) { el.appendChild(document.createTextNode(text.slice(pos))); break; }
      if (best > pos) el.appendChild(document.createTextNode(text.slice(pos, best)));
      var mk = document.createElement("mark");
      mk.textContent = text.slice(best, best + len);
      el.appendChild(mk);
      pos = best + len;
    }
  }

  function snippet(d, terms, phrase) {
    var at = phrase ? firstOf(d.nx, phrase) : -1;
    for (var i = 0; at === -1 && i < terms.length; i++) {
      var j = firstOf(d.nx, terms[i]);
      if (j !== -1) at = j;
    }
    if (at === -1) at = 0;
    var start = Math.max(0, at - 90), end = Math.min(d.text.length, at + 170);
    if (start > 0) { var sp = d.text.indexOf(" ", start); if (sp !== -1 && sp < at) start = sp + 1; }
    if (end < d.text.length) { var sp2 = d.text.lastIndexOf(" ", end); if (sp2 > at) end = sp2; }
    return (start > 0 ? "…" : "") + d.text.slice(start, end) + (end < d.text.length ? "…" : "");
  }

  function render(q) {
    results.textContent = "";
    var r = search(q);
    if (!q.trim()) { status.textContent = ""; return; }
    if (!r.terms.length) { status.textContent = "Type a word or phrase to search."; return; }
    var n = r.hits.length;
    status.textContent = n === 0
      ? "No essays or poems contain all of those words."
      : n + (n === 1 ? " essay or poem" : " essays and poems") + " found.";
    r.hits.forEach(function (h) {
      var d = h.doc;
      var a = document.createElement("a");
      a.className = "essay-row search-result";
      a.href = "essays/" + d.slug + ".html";
      var wrap = document.createElement("span");
      var h3 = document.createElement("h3");
      appendMarked(h3, d.title, r.terms);
      var p = document.createElement("p");
      p.className = "excerpt";
      appendMarked(p, snippet(d, r.terms, r.phrase), r.terms);
      var tags = document.createElement("span");
      tags.className = "tag-list";
      d.cats.forEach(function (c) {
        var t = document.createElement("span");
        t.className = "tag";
        t.textContent = c;
        tags.appendChild(t);
      });
      wrap.appendChild(h3); wrap.appendChild(p); wrap.appendChild(tags);
      a.appendChild(wrap);
      results.appendChild(a);
    });
  }

  function currentQuery() {
    var m = /[?&]q=([^&]*)/.exec(window.location.search);
    if (!m) return "";
    try { return decodeURIComponent(m[1].replace(/\+/g, " ")); } catch (e) { return ""; }
  }

  var timer = null;
  input.addEventListener("input", function () {
    clearTimeout(timer);
    timer = setTimeout(function () {
      render(input.value);
      try {
        var url = input.value.trim() ? "?q=" + encodeURIComponent(input.value) : window.location.pathname;
        window.history.replaceState(null, "", url);
      } catch (e) { /* history API unavailable, e.g. some file:// contexts */ }
    }, 150);
  });
  form.addEventListener("submit", function (ev) {
    ev.preventDefault();
    render(input.value);
  });

  var q0 = currentQuery();
  if (q0) { input.value = q0; render(q0); }
  input.focus();
})();
